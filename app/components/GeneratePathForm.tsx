// ─── Roadmap Generator ────────────────────────────────────────────────────────

interface RoadmapGeneratorProps {
    steps: string[];
    skills: string;
    goal: string;
    onDownload?: () => void;
}

function RoadmapGenerator({ steps, skills, goal, onDownload }: RoadmapGeneratorProps) {
    const canvasRef = useRef<HTMLCanvasElement>(null);
    const [isGenerating, setIsGenerating] = useState(false);
    const [roadmapGenerated, setRoadmapGenerated] = useState(false);

    const CANVAS_WIDTH = 1200;
    const CANVAS_HEIGHT = 800;
    const NODE_RADIUS = 40;
    const SPACING_X = 180;
    const SPACING_Y = 120;

    const COLORS = {
        background: "#0a0a1a",
        accent: "#3c1a6b",
        accentLight: "#6b4ba1",
        white: "#ffffff",
        gray: "#a0a0a0",
        connection: "#4a2c7a",
    };

    const fetchSimplifiedSteps = async (): Promise<string[]> => {
        try {
            const response = await fetch("/generate-roadmap-steps", {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify({ skills, goal }),
            });
            if (!response.ok) throw new Error("Failed");
            const data = await response.json();
            return data.steps || steps;
        } catch {
            return steps;
        }
    };

    const simplifyStepText = (stepText: string, stepIndex: number): string => {
        const text = stepText.replace(/^\d+\.\s*/, "").toLowerCase().trim();

        const extractors: Array<{ regex: RegExp; format: (m: string) => string }> = [
            { regex: /\b(python|java|javascript|js|typescript|react|angular|vue|node\.?js?|express|django|flask|spring|html|css|sass|scss|bootstrap|tailwind)\b/i, format: (m) => `Learn ${capitalizeFirst(m)}` },
            { regex: /\b(mysql|postgresql|mongodb|redis|sqlite|database|sql)\b/i, format: (m) => `Learn ${capitalizeFirst(m === "database" ? "Databases" : m)}` },
            { regex: /\b(docker|kubernetes|aws|azure|gcp|git|github|gitlab|ci\/cd|devops)\b/i, format: (m) => `Learn ${capitalizeFirst(m)}` },
            { regex: /build.*?(project|application|app|website|portfolio)/i, format: () => "Build Projects" },
            { regex: /create.*?(portfolio|website|project|application)/i, format: () => "Create Portfolio" },
            { regex: /network|networking/i, format: () => "Network & Connect" },
            { regex: /apply.*?(job|position|role)/i, format: () => "Apply for Jobs" },
            { regex: /deploy|deployment/i, format: () => "Deploy Apps" },
        ];

        for (const extractor of extractors) {
            const match = text.match(extractor.regex);
            if (match) return extractor.format(match[1] || match[0]);
        }

        const words = text
            .replace(/[^\w\s]/g, " ")
            .split(" ")
            .filter(
                (w) =>
                    w.length > 2 &&
                    !["the", "and", "for", "your", "you", "with", "that", "this", "from", "into", "about", "will", "can", "should", "would", "could", "must", "need", "want", "make", "get", "use", "work", "learn", "study", "understand", "know", "take", "start", "begin", "complete"].includes(w.toLowerCase())
            );

        if (words.length >= 2) return `${capitalizeFirst(words[0])} ${capitalizeFirst(words[1])}`;
        if (words.length === 1) return capitalizeFirst(words[0]);
        return `Step ${stepIndex + 1}`;
    };

    const generateRoadmap = async () => {
        setIsGenerating(true);
        await new Promise((r) => setTimeout(r, 500));

        const simplifiedSteps = await fetchSimplifiedSteps();
        const canvas = canvasRef.current;
        if (!canvas) return;

        const ctx = canvas.getContext("2d");
        if (!ctx) return;

        canvas.width = CANVAS_WIDTH;
        canvas.height = CANVAS_HEIGHT;

        ctx.fillStyle = COLORS.background;
        ctx.fillRect(0, 0, CANVAS_WIDTH, CANVAS_HEIGHT);

        ctx.strokeStyle = "rgba(60, 26, 107, 0.1)";
        ctx.lineWidth = 1;
        for (let x = 0; x < CANVAS_WIDTH; x += 50) {
            ctx.beginPath(); ctx.moveTo(x, 0); ctx.lineTo(x, CANVAS_HEIGHT); ctx.stroke();
        }
        for (let y = 0; y < CANVAS_HEIGHT; y += 50) {
            ctx.beginPath(); ctx.moveTo(0, y); ctx.lineTo(CANVAS_WIDTH, y); ctx.stroke();
        }

        ctx.fillStyle = COLORS.white;
        ctx.font = "bold 32px Arial, sans-serif";
        ctx.textAlign = "center";
        ctx.fillText("🎯 Learning Roadmap", CANVAS_WIDTH / 2, 60);
        ctx.font = "18px Arial, sans-serif";
        ctx.fillStyle = COLORS.gray;
        ctx.fillText(`From: ${skills} → To: ${goal}`, CANVAS_WIDTH / 2, 90);

        const positions: { x: number; y: number; isEven: boolean }[] = [];
        const startY = 200;
        const centerX = CANVAS_WIDTH / 2;

        simplifiedSteps.forEach((_, index) => {
            const isEven = index % 2 === 0;
            const x = centerX + (isEven ? -SPACING_X : SPACING_X);
            const y = startY + index * SPACING_Y;
            positions.push({ x, y, isEven });
        });

        ctx.strokeStyle = COLORS.connection;
        ctx.lineWidth = 3;
        ctx.setLineDash([5, 5]);

        for (let i = 0; i < positions.length - 1; i++) {
            const current = positions[i];
            const next = positions[i + 1];
            ctx.shadowColor = COLORS.accent;
            ctx.shadowBlur = 10;
            ctx.beginPath();
            ctx.moveTo(current.x, current.y + NODE_RADIUS);
            const midY = (current.y + next.y) / 2;
            ctx.quadraticCurveTo(current.x, midY, next.x, next.y - NODE_RADIUS);
            ctx.stroke();
            ctx.shadowBlur = 0;
        }
        ctx.setLineDash([]);

        simplifiedSteps.forEach((step, index) => {
            const pos = positions[index];
            const simplifiedText = simplifyStepText(step.replace(/^\d+\.\s*/, ""), index);

            const gradient = ctx.createRadialGradient(pos.x, pos.y, 0, pos.x, pos.y, NODE_RADIUS);
            gradient.addColorStop(0, COLORS.accentLight);
            gradient.addColorStop(1, COLORS.accent);

            ctx.fillStyle = gradient;
            ctx.shadowColor = COLORS.accent;
            ctx.shadowBlur = 15;
            ctx.beginPath();
            ctx.arc(pos.x, pos.y, NODE_RADIUS, 0, 2 * Math.PI);
            ctx.fill();
            ctx.shadowBlur = 0;

            ctx.fillStyle = COLORS.white;
            ctx.font = "bold 24px Arial, sans-serif";
            ctx.textAlign = "center";
            ctx.fillText((index + 1).toString(), pos.x, pos.y + 8);

            ctx.font = "bold 18px Arial, sans-serif";
            const words = simplifiedText.split(" ");
            const maxWidth = 160;
            let lines: string[] = [];
            let currentLine = words[0];
            for (let i = 1; i < words.length; i++) {
                const testLine = currentLine + " " + words[i];
                if (ctx.measureText(testLine).width > maxWidth) {
                    lines.push(currentLine);
                    currentLine = words[i];
                } else {
                    currentLine = testLine;
                }
            }
            lines.push(currentLine);
            if (lines.length > 2) lines = [lines[0], lines[1].substring(0, 10) + "..."];

            const textX = pos.isEven ? pos.x - NODE_RADIUS - 15 : pos.x + NODE_RADIUS + 15;
            ctx.textAlign = pos.isEven ? "right" : "left";
            lines.forEach((line, li) => {
                ctx.fillText(line, textX, pos.y + (li - lines.length / 2) * 22 + 5);
            });
        });

        ctx.fillStyle = COLORS.gray;
        ctx.font = "14px Arial, sans-serif";
        ctx.textAlign = "center";
        ctx.fillText(`Generated by PathFlow AI • ${new Date().toLocaleDateString()}`, CANVAS_WIDTH / 2, CANVAS_HEIGHT - 30);

        setRoadmapGenerated(true);
        setIsGenerating(false);
    };

    const downloadRoadmap = () => {
        const canvas = canvasRef.current;
        if (!canvas) return;
        canvas.toBlob((blob) => {
            if (!blob) return;
            const url = URL.createObjectURL(blob);
            const link = document.createElement("a");
            link.download = `learning-roadmap-${Date.now()}.jpg`;
            link.href = url;
            document.body.appendChild(link);
            link.click();
            document.body.removeChild(link);
            URL.revokeObjectURL(url);
            if (onDownload) onDownload();
        }, "image/jpeg", 0.9);
    };

    useEffect(() => {
        if (steps && steps.length > 0) generateRoadmap();
        // eslint-disable-next-line react-hooks/exhaustive-deps
    }, [steps]);

    if (!steps || steps.length === 0) {
        return (
            <div style={{ padding: "2rem", textAlign: "center", color: "#a0a0a0", backgroundColor: "rgba(0,0,0,0.7)", borderRadius: "10px", border: "2px dashed rgba(60,26,107, 0.3)" }}>
                <div style={{ fontSize: "3rem", marginBottom: "1rem" }}>🗺️</div>
                <p>Generate a learning path first to create your roadmap!</p>
            </div>
        );
    }

    return (
        <div style={{ marginTop: "2rem", backgroundColor: "rgba(0,0,0,0.7)", padding: "2rem", borderRadius: "15px", border: "1px solid rgba(60,26,107, 0.3)" }}>
            <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", marginBottom: "1.5rem", flexWrap: "wrap", gap: "1rem" }}>
                <h2 style={{ margin: 0, color: "white", fontSize: "1.8rem" }}>🗺️ Visual Roadmap</h2>
                <div style={{ display: "flex", gap: "1rem", alignItems: "center" }}>
                    <button onClick={generateRoadmap} disabled={isGenerating} style={{ padding: "10px 20px", backgroundColor: isGenerating ? "#6c757d" : "#3c1a6b", color: "white", border: "none", borderRadius: "8px", cursor: isGenerating ? "not-allowed" : "pointer", fontSize: "1rem", fontWeight: "bold" }}>
                        {isGenerating ? "🔄 Generating..." : "🎨 Regenerate"}
                    </button>
                    {roadmapGenerated && (
                        <button onClick={downloadRoadmap} style={{ padding: "10px 20px", backgroundColor: "#28a745", color: "white", border: "none", borderRadius: "8px", cursor: "pointer", fontSize: "1rem", fontWeight: "bold" }}>
                            📥 Download JPG
                        </button>
                    )}
                </div>
            </div>
            <div style={{ display: "flex", justifyContent: "center", backgroundColor: "rgba(0,0,0,0.5)", borderRadius: "10px", padding: "1rem" }}>
                <canvas ref={canvasRef} style={{ maxWidth: "100%", height: "auto", borderRadius: "8px", display: isGenerating ? "none" : "block" }} />
            </div>
            {roadmapGenerated && (
                <div style={{ marginTop: "1rem", padding: "1rem", backgroundColor: "rgba(40,167,69,0.2)", borderRadius: "8px", border: "1px solid rgba(40,167,69,0.3)", textAlign: "center", color: "#d4edda" }}>
                    ✅ Roadmap generated! Click &quot;Download JPG&quot; to save.
                </div>
            )}
        </div>
    );
}

// ─── Main: Generate Path Form ─────────────────────────────────────────────────

export default function GeneratePathForm() {
    const { loading, setLoading, error, setError } = useAppContext();
    const [skills, setSkills] = useState("");
    const [goal, setGoal] = useState("");
    const [result, setResult] = useState<{ steps: string[]; skills: string; goal: string; metadata: { generatedBy: string; responseTime: number } } | null>(null);
    const [validationErrors, setValidationErrors] = useState<{ skills?: string; goal?: string }>({});
    const [showRoadmap, setShowRoadmap] = useState(false);

    const validateForm = (): boolean => {
        const errors: { skills?: string; goal?: string } = {};
        if (!skills.trim()) errors.skills = "Skills are required";
        else if (skills.length > 200) errors.skills = "Skills description is too long (max 200 characters)";
        if (!goal.trim()) errors.goal = "Goal is required";
        else if (goal.length > 100) errors.goal = "Goal description is too long (max 100 characters)";
        setValidationErrors(errors);
        return Object.keys(errors).length === 0;
    };

    const handleSubmit = async (e: React.FormEvent) => {
        e.preventDefault();
        if (!validateForm()) return;

        setLoading(true);
        setError("");
        setResult(null);
        setShowRoadmap(false);

        try {
            const response = await fetch("/api/generate-path", {
                method: "POST",
                headers: { "Content-Type": "application/json", Accept: "application/json" },
                body: JSON.stringify({ skills: skills.trim(), goal: goal.trim() }),
            });

            if (!response.ok) {
                const errorData = await response.json().catch(() => ({}));
                throw new Error((errorData as { error?: string }).error || `Server error: ${response.status}`);
            }

            const data = await response.json();
            if (!data.success || !data.steps || data.steps.length === 0) {
                throw new Error("Invalid response from server");
            }

            setResult({ steps: data.steps, skills: skills.trim(), goal: goal.trim(), metadata: data.metadata });
        } catch (err) {
            setError((err as Error).message || "Failed to generate learning path. Please try again.");
        } finally {
            setLoading(false);
        }
    };

    const handleReset = () => {
        setSkills(""); setGoal(""); setResult(null); setError(""); setValidationErrors({}); setShowRoadmap(false);
    };

    const inputStyle: React.CSSProperties = {
        width: "100%", padding: "12px 16px", borderRadius: "8px",
        border: "1px solid rgba(60,26,107, 0.3)", fontSize: "1rem",
        transition: "border-color 0.3s ease", boxSizing: "border-box",
        backgroundColor: "rgba(0, 0, 0, 0.7)", color: "white",
    };

    return (
        <div style={{ padding: "2rem", maxWidth: "1200px", margin: "0 auto", fontFamily: "Arial, sans-serif", color: "white", minHeight: "100vh" }}>
            <div style={{ backgroundColor: "rgba(0, 0, 0, 0.7)", padding: "2rem", borderRadius: "15px", boxShadow: "0 4px 20px rgba(0,0,0,0.5)", border: "1px solid rgba(60,26,107, 0.3)" }}>
                <h1 style={{ textAlign: "center", color: "white", marginBottom: "2rem", fontSize: "2.5rem" }}>
                    🎯 Generate Your Learning Path
                </h1>

                <form onSubmit={handleSubmit} style={{ marginBottom: "2rem" }}>
                    {/* Skills */}
                    <div style={{ marginBottom: "1.5rem" }}>
                        <label style={{ display: "block", marginBottom: "0.5rem", fontWeight: "bold", color: "white" }}>
                            Your Current Skills *
                        </label>
                        <input type="text" placeholder="e.g., Python, HTML, CSS, Basic JavaScript" value={skills}
                            onChange={(e) => { setSkills(e.target.value); if (validationErrors.skills) setValidationErrors((p) => ({ ...p, skills: undefined })); }}
                            style={{ ...inputStyle, border: validationErrors.skills ? "2px solid #dc3545" : inputStyle.border }} maxLength={200} disabled={loading} />
                        {validationErrors.skills && <p style={{ color: "#dc3545", fontSize: "0.9rem", margin: "0.5rem 0 0 0" }}>{validationErrors.skills}</p>}
                        <p style={{ fontSize: "0.8rem", color: "#a0a0a0", margin: "0.5rem 0 0 0" }}>{skills.length}/200 characters</p>
                    </div>

                    {/* Goal */}
                    <div style={{ marginBottom: "1.5rem" }}>
                        <label style={{ display: "block", marginBottom: "0.5rem", fontWeight: "bold", color: "white" }}>
                            Your Career Goal *
                        </label>
                        <input type="text" placeholder="e.g., Full Stack Developer, Data Scientist, UX Designer" value={goal}
                            onChange={(e) => { setGoal(e.target.value); if (validationErrors.goal) setValidationErrors((p) => ({ ...p, goal: undefined })); }}
                            style={{ ...inputStyle, border: validationErrors.goal ? "2px solid #dc3545" : inputStyle.border }} maxLength={100} disabled={loading} />
                        {validationErrors.goal && <p style={{ color: "#dc3545", fontSize: "0.9rem", margin: "0.5rem 0 0 0" }}>{validationErrors.goal}</p>}
                        <p style={{ fontSize: "0.8rem", color: "#a0a0a0", margin: "0.5rem 0 0 0" }}>{goal.length}/100 characters</p>
                    </div>

                    <div style={{ display: "flex", gap: "1rem", flexWrap: "wrap" }}>
                        <button type="submit" disabled={loading || !skills.trim() || !goal.trim()}
                            style={{ flex: "1", minWidth: "200px", padding: "12px 24px", backgroundColor: (loading || !skills.trim() || !goal.trim()) ? "#6c757d" : "#3c1a6b", color: "white", border: "none", borderRadius: "8px", cursor: (loading || !skills.trim() || !goal.trim()) ? "not-allowed" : "pointer", fontSize: "1.1rem", fontWeight: "bold" }}>
                            {loading ? "🔄 Generating..." : "🚀 Generate Path"}
                        </button>
                        {result && (
                            <button type="button" onClick={handleReset}
                                style={{ padding: "12px 24px", backgroundColor: "#6c757d", color: "white", border: "none", borderRadius: "8px", cursor: "pointer", fontSize: "1.1rem", fontWeight: "bold" }}>
                                🔄 Start Over
                            </button>
                        )}
                    </div>
                </form>

                {error && (
                    <div style={{ backgroundColor: "rgba(248,215,218,0.2)", color: "#f5c6cb", padding: "1rem", borderRadius: "8px", border: "1px solid rgba(245,198,203,0.3)", marginBottom: "1rem", textAlign: "center" }}>
                        ⚠️ {error}
                    </div>
                )}

                {loading && <LoadingSpinner message="Generating your personalized learning path..." />}

                {result && !loading && (
                    <>
                        {/* View Toggle */}
                        <div style={{ display: "flex", justifyContent: "center", gap: "1rem", marginBottom: "2rem" }}>
                            {[{ label: "📋 Text View", active: !showRoadmap, onClick: () => setShowRoadmap(false) },
                            { label: "🗺️ Roadmap View", active: showRoadmap, onClick: () => setShowRoadmap(true) }].map(({ label, active, onClick }) => (
                                <button key={label} onClick={onClick}
                                    style={{ padding: "10px 20px", backgroundColor: active ? "#3c1a6b" : "rgba(60,26,107, 0.3)", color: "white", border: "1px solid rgba(60,26,107, 0.5)", borderRadius: "8px", cursor: "pointer", fontSize: "1rem", fontWeight: "bold" }}>
                                    {label}
                                </button>
                            ))}
                        </div>

                        {showRoadmap ? (
                            <RoadmapGenerator steps={result.steps} skills={result.skills} goal={result.goal} onDownload={() => console.log("Downloaded!")} />
                        ) : (
                            <LearningPathDisplay steps={result.steps} skills={result.skills} goal={result.goal} metadata={result.metadata} />
                        )}
                    </>
                )}

                {!loading && !result && !error && (
                    <div style={{ textAlign: "center", color: "#a0a0a0", padding: "2rem", backgroundColor: "rgba(0,0,0,0.7)", borderRadius: "10px", border: "2px dashed rgba(60,26,107, 0.3)" }}>
                        <div style={{ fontSize: "3rem", marginBottom: "1rem" }}>🎯</div>
                        <p style={{ fontSize: "1.1rem", margin: 0 }}>Enter your skills and career goal above to get started!</p>
                    </div>
                )}
            </div>
        </div>
    );
}
